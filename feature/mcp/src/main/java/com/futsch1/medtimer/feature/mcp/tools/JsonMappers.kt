// The app stores "no date" as the epoch, which the model must never see as a real date.
internal fun LocalDate.toJsonOrNull(): String? = takeIf { it != LocalDate.EPOCH }?.toString()

internal fun Instant.toIsoString(zone: ZoneId): String = DateTimeFormatter.ISO_OFFSET_DATE_TIME.format(atZone(zone))

internal fun Medicine.toSummaryJson(): JsonObject = buildJsonObject {
    // Reminders for running out of stock or expiring are generated by the app and are not "reminders" in the user's sense.
    val doseReminders = reminders.filterNot { it.isOutOfStockOrExpirationReminder }
    put("id", id)
    put("name", name)
    put("unit", unit)
    // Without stock management the amount is just 0, which would read as "none left".
    put("stock", if (isStockManagementActive()) JsonPrimitive(amount) else JsonNull)
    put("tags", JsonArray(tags.map { JsonPrimitive(it.name) }))
    put("expiration_date", expirationDate.toJsonOrNull())
    put("notification_priority", MedicinePriority.of(this@toSummaryJson).name)
    put("reminder_count", doseReminders.size)
    put("active_reminder_count", doseReminders.count { it.active })
}

internal fun Medicine.toDetailJson(zone: ZoneId): JsonObject = buildJsonObject {
    toSummaryJson().forEach { (key, value) -> put(key, value) }
    put("refill_size", refillSize)
    put("notes", notes)
    put("production_date", productionDate.toJsonOrNull())
    put("cannot_be_skipped", cannotBeSkipped)
    put("reminders", JsonArray(reminders.map { it.toJson(zone) }))
}

internal fun Reminder.toJson(zone: ZoneId): JsonObject = buildJsonObject {
    val type = reminderType
    put("id", id)
    put("medicine_id", medicineRelId)
    put("type", type.name)
    put("active", active)
    put("amount", amount)
    put("instructions", instructions.orEmpty())
    when (type) {
        ReminderType.TIME_BASED -> {
            put("time", time.getLocalTime().toString())
            // An empty list means "every day" in the app; spell it out so it cannot be read as "never".
            put("days", JsonArray(days.ifEmpty { DayOfWeek.entries }.sorted().map { JsonPrimitive(it.name) }))
            put("active_days_of_month", JsonArray(activeDaysOfMonth.map(::JsonPrimitive)))
            put("cycle", cycleJson())
            put("period_start", periodStart.toJsonOrNull())
            put("period_end", periodEnd.toJsonOrNull())
        }

        ReminderType.LINKED -> {
            put("linked_reminder_id", linkedReminderId)
            put("delay_minutes", time.minutes)
        }

        ReminderType.CONTINUOUS_INTERVAL -> {
            put("interval_minutes", time.minutes)
            put("interval_start", intervalStart.toIsoString(zone))
            put("interval_starts_from_processed", intervalStartsFromProcessed)
        }

        ReminderType.WINDOWED_INTERVAL -> {
            put("interval_minutes", time.minutes)
            put("window_start", intervalStartTimeOfDay.toString())
            put("window_end", intervalEndTimeOfDay.toString())
        }

        ReminderType.OUT_OF_STOCK -> {
            put("out_of_stock_threshold", outOfStockThreshold)
            put("out_of_stock_reminder", outOfStockReminderType.name)
        }

        ReminderType.EXPIRATION_DATE -> {
            put("expiration_reminder", expirationReminderType.name)
            put("time", time.getLocalTime().toString())
        }

        ReminderType.REFILL -> Unit
    }
    if (!isOutOfStockOrExpirationReminder) {
        put("variable_amount", variableAmount)
        put("automatically_taken", automaticallyTaken)
        put("notification_priority", notificationImportance.name)
    }
    put("editable_via_mcp", !isOutOfStockOrExpirationReminder)
}

private fun Reminder.cycleJson(): JsonElement =
    if (pauseDays > 0) {
        buildJsonObject {
            put("consecutive_days", consecutiveDays)
            put("pause_days", pauseDays)
            put("cycle_start_day", cycleStartDay.toJsonOrNull())
        }
    } else {
        JsonNull
    }

internal fun ReminderEvent.toJson(zone: ZoneId, medicineId: Int?): JsonObject = buildJsonObject {
    put("event_id", reminderEventId)
    // Cyclic reminders carry a counter such as " (1/3)" in the stored name.
    put("medicine_name", MedicineHelper.normalizeMedicineName(medicineName))
    put("medicine_id", medicineId)
    put("amount", amount)
    put("status", status.name)
    put("reminded_at", remindedTimestamp.toIsoString(zone))
    put("processed_at", processedTimestamp.takeIf { it != Instant.EPOCH }?.toIsoString(zone))
    put("reminder_type", reminderType.name)
}
